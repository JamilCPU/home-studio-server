"""Transcript fetching for YoutubeBrainwash.

Uses youtube_transcript_api to retrieve video transcripts
for downstream content analysis and scoring.
"""

from __future__ import annotations

import logging
from typing import Any

from youtube_transcript_api import (
    NoTranscriptFound,
    TranscriptsDisabled,
    YouTubeTranscriptApi,
)

from src.models import TranscriptResult

logger = logging.getLogger(__name__)


def fetch_transcript(
    video_id: str,
    language: str = "en",
) -> TranscriptResult | None:
    """Fetch a single video transcript.

    Tries the requested language first, then the auto-generated variant.
    Returns ``None`` when no transcript is available.
    """
    try:
        transcript_list: list[dict[str, Any]] = YouTubeTranscriptApi.get_transcript(
            video_id,
            languages=[language, f"{language}-auto"],
        )
        text = " ".join(entry["text"] for entry in transcript_list)

        # Determine whether the transcript is auto-generated by checking
        # if the "-auto" language variant was the one returned.
        is_auto = _is_auto_generated(video_id, language)

        logger.info(
            "Fetched transcript for %s (%d chars, auto=%s)",
            video_id,
            len(text),
            is_auto,
        )
        return TranscriptResult(
            video_id=video_id,
            text=text,
            language=language,
            is_auto_generated=is_auto,
        )

    except TranscriptsDisabled:
        logger.warning("Transcripts disabled for video %s", video_id)
        return None

    except NoTranscriptFound:
        logger.warning(
            "No transcript found for video %s in language '%s'",
            video_id,
            language,
        )
        return None

    except Exception:
        logger.exception("Unexpected error fetching transcript for %s", video_id)
        return None


def fetch_transcripts_batch(
    video_ids: list[str],
    language: str = "en",
) -> dict[str, TranscriptResult]:
    """Fetch transcripts for multiple videos.

    Returns a dict mapping ``video_id`` to ``TranscriptResult``
    for every video where a transcript was successfully retrieved.
    """
    results: dict[str, TranscriptResult] = {}

    for video_id in video_ids:
        result = fetch_transcript(video_id, language=language)
        if result is not None:
            results[video_id] = result

    logger.info(
        "Fetched %d/%d transcripts",
        len(results),
        len(video_ids),
    )
    return results


def truncate_transcript(text: str, max_chars: int = 3000) -> str:
    """Truncate transcript text for prompt size management.

    Tries to cut at a sentence boundary (the last ``". "`` before
    *max_chars*).  Falls back to a hard cut if no sentence boundary
    is found.
    """
    if len(text) <= max_chars:
        return text

    # Try to find a sentence boundary before the limit.
    boundary = text.rfind(". ", 0, max_chars)
    if boundary != -1:
        return text[: boundary + 1]

    # No clean sentence boundary -- hard cut.
    return text[:max_chars]


def _is_auto_generated(video_id: str, language: str) -> bool:
    """Check whether the transcript for *video_id* is auto-generated.

    Lists all available transcripts and inspects the ``is_generated``
    flag.  Returns ``True`` if only an auto-generated transcript exists
    for the requested language, or ``False`` if a manual one is present.
    Defaults to ``False`` on any error.
    """
    try:
        transcript_list = YouTubeTranscriptApi.list_transcripts(video_id)
        try:
            transcript = transcript_list.find_transcript([language])
            return transcript.is_generated
        except NoTranscriptFound:
            pass
        try:
            transcript = transcript_list.find_transcript([f"{language}-auto"])
            return transcript.is_generated
        except NoTranscriptFound:
            pass
    except Exception:
        logger.debug(
            "Could not determine auto-generated status for %s",
            video_id,
        )
    return False
